// يفتح دالة فورية التنفيذ لعزل منطق لوحة الإحصائيات التفصيلية عن النطاق العام للمتصفح.
(function () {
  // يفعّل الوضع الصارم لضمان سلامة العمليات الحسابية لتجميع البيانات اليومية والأسبوعية.
  "use strict";

  // يعرّف مفتاح التخزين الموحّد الذي يسجل فيه المحرك mustaqbalat-engine.js دقائق التفعيل واستهلاك النظام يومياً.
  const STORAGE_KEY_USAGE = "mustaqbalat_usage_v1";
  // يحدد المدى الزمني الابتدائي المعروض عند فتح اللوحة بآخر 7 أيام ("7d").
  let currentHorizon = "7d";
  // ينشئ متغيراً منطقياً للتبديل بين السجل الفعلي للمستخدم وبين بيانات المحاكاة التوضيحية لثمانية أسابيع.
  let demoMode = false;

  // يفحص ما إذا كانت اللوحة تعمل داخل سياق إضافة المتصفح الحقيقية للوصول إلى chrome.storage.local.
  const isExtensionEnv =
    // يتحقق أولاً من توفر الكائن العام chrome في بيئة التشغيل.
    typeof chrome !== "undefined" &&
    // يتحقق ثانياً من توفر واجهة التخزين chrome.storage.
    chrome.storage &&
    // يتحقق ثالثاً من توفر مساحة التخزين المحلية الدائمة local.
    chrome.storage.local &&
    // يتحقق رابعاً من قابلية استدعاء دالة القراءة get.
    typeof chrome.storage.local.get === "function";

  // يعرّف دالة مختصرة لجلب عناصر لوحة dashboard.html عبر معرّفها الفريد.
  const $ = (id) => document.getElementById(id);

  // Hide studio back-link if inside packed extension
  // يفحص تشغيل الصفحة من داخل بروتوكول الإضافة لإخفاء زر الرجوع الخاص بمنصة الويب الخارجية.
  if (isExtensionEnv && location.protocol.includes("extension")) {
    // يجلب عنصر رابط العودة للمنصة الرئيسية من شريط الأدوات العلوي.
    const link = $("backStudioLink");
    // يخفي الرابط في سياق الإضافة المستقلة لأنها تعمل بمعزل عن ملف index.html.
    if (link) link.style.display = "none";
    // يغلق شرط فحص بروتوكول الإضافة.
  }

  // يعرّف دالة غير متزامنة لقراءة سجل الاستهلاك الفعلي المتراكم عبر الأيام والأسابيع من التخزين المناسب.
  async function loadRealHistory() {
    // يستخدم تخزين الإضافة الرسمي إذا كانت البيئة إضافة متصفح مثبتة.
    if (isExtensionEnv) {
      // يغلّف عملية الجلب غير المتزامنة في وعد برمجي (Promise).
      return new Promise((resolve) => {
        // يطلب قراءة الكائن المرتبط بالمفتاح STORAGE_KEY_USAGE.
        chrome.storage.local.get([STORAGE_KEY_USAGE], (res) => {
          // يعيد خريطة التواريخ المسجلة أو كائناً فارغاً إن لم تتراكم بيانات بعد.
          resolve((res && res[STORAGE_KEY_USAGE]) || {});
          // يغلق استدعاء الجلب من تخزين الإضافة.
        });
        // يغلق وعد القراءة من الإضافة.
      });
      // يغلق فرع قراءة تخزين الإضافة.
    }
    // يلجأ لقراءة localStorage القياسي عند فتح اللوحة من منصة الويب السحابية أو المحاكي.
    try {
      // يقرأ النص الخام للسجل التاريخي من تخزين المتصفح المحلي.
      const raw = localStorage.getItem(STORAGE_KEY_USAGE);
      // يحول النص إلى كائن جافاسكربت أو يعيد كائناً فارغاً عند عدم وجود سجل سابق.
      return raw ? JSON.parse(raw) : {};
      // يلتقط أي خطأ في تحليل النص المخزن لضمان عدم تعطل اللوحة.
    } catch (_) {
      // يعيد كائناً فارغاً آمناً عند حدوث استثناء.
      return {};
      // يغلق كتلة الحماية.
    }
    // يغلق دالة جلب السجل الحقيقي loadRealHistory.
  }

  // يعرّف دالة توليد بيانات توضيحية واقعية تمتد لـ 56 يوماً (8 أسابيع كاملة) لمعاينة شكل المخططات الأسبوعية دون المساس بالسجل الحقيقي.
  function generateSyntheticMultiWeekHistory() {
    // ينشئ كائناً فارغاً لتعبئته بسجلات الأيام الـ 56 الماضية.
    const out = {};
    // يلتقط التاريخ الحالي كنقطة مرجعية لحساب التواريخ السابقة بدقة.
    const now = new Date();
    // يبدأ حلقة عكسية من قبل 55 يوماً وصولاً إلى اليوم الحالي (0).
    for (let i = 55; i >= 0; i--) {
      // ينسخ التاريخ الحالي لتعديله دون التأثير على الكائن المرجعي now.
      const d = new Date(now);
      // يرجع بالتاريخ للوراء بمقدار i يوماً لتحديد تاريخ اليوم المستهدف في السلسلة.
      d.setDate(now.getDate() - i);
      // يستخرج مفتاح التاريخ القياسي بصيغة YYYY-MM-DD المطابقة لما يكتبه المحرك الأساسي.
      const key = d.toISOString().slice(0, 10);
      // يحسب معامل تموج جيبي ناعم لمحاكاة التفاوت الطبيعي في ساعات القراءة بين أيام الأسبوع.
      const wave = Math.sin(i * 0.45) * 0.35 + 0.85;
      // يحسب دقائق التفعيل اليومية بناءً على المعامل السابق لتتراوح واقعياً حول ساعة إلى ساعتين يومياً.
      const mins = Math.round((42 + ((i * 17) % 65)) * wave);
      // يشتق عدد الصفحات المحمية في ذلك اليوم بالتناسب مع دقائق التصفح.
      const pages = Math.max(3, Math.round(mins / 4.2));
      // يحسب عدد ملفات الـ PDF المقروءة في بعض الأيام بنسبة واقعية من عدد الصفحات.
      const pdfs = i % 3 === 0 ? Math.max(1, Math.round(pages * 0.18)) : 0;
      // يحدد متوسط استهلاك الذاكرة الخفيف جداً (بين 18 و30 كيلوبايت) المطابق لأداء المحرك الفعلي.
      const avgKB = 18 + (i % 7) * 2;
      // يسجل كائن إحصائيات هذا اليوم تحت مفتاح التاريخ key داخل الخريطة out.
      out[key] = {
        // يحفظ سلسلة التاريخ المرجعية.
        date: key,
        // يسجل إجمالي دقائق تشغيل التعتيم في هذا اليوم.
        activeMinutes: mins,
        // يسجل عدد صفحات الويب التي طُبّقت عليها الحماية البصرية.
        pagesCount: pages,
        // يسجل عدد ملفات الـ PDF التي جرى تعتيمها.
        pdfsCount: pdfs,
        // يحسب حصة الوضع الداكن بنحو 58% من وقت التشغيل الكلي.
        darkModeMinutes: Math.round(mins * 0.58),
        // يحسب حصة تلوين الشاشة HEX بنحو 34% من وقت التشغيل.
        tintMinutes: Math.round(mins * 0.34),
        // يحسب إجمالي زمن معالجة المعالج بالمللي ثانية (أجزاء طفيفة من الثانية طوال اليوم).
        totalApplyMs: Number((pages * 0.38).toFixed(2)),
        // يسجل متوسط البصمة التخزينية والذاكرية بالكيلوبايت.
        avgFootprintKB: avgKB,
        // يسجل أقصى ذروة ذاكرة وصل إليها المحرك في ذلك اليوم بالكيلوبايت.
        peakFootprintKB: avgKB + 9
        // يغلق كائن بيانات اليوم الواحد.
      };
      // يغلق حلقة توليد الأيام الـ 56.
    }
    // يعيد خريطة الأسابيع الثمانية الكاملة للعرض المؤقت.
    return out;
    // يغلق دالة المحاكاة generateSyntheticMultiWeekHistory.
  }

  // يعرّف دالة تجميع السجلات التاريخية في فئات زمنية (يومية لـ 7/14 يوماً، أو أسبوعية مجمّعة لـ 4/8 أسابيع).
  function buildBuckets(historyMap, horizon) {
    // يلتقط تاريخ اللحظة الحالية لبناء النوافذ الزمنية الرجعية.
    const now = new Date();
    // ينشئ مصفوفة الفئات الزمنية المرتبة من الأقدم للأحدث تمهيداً لرسمها بيانياً.
    const buckets = [];

    // يفحص ما إذا كان العرض المطلوب يومياً ("7d" أو "14d").
    if (horizon === "7d" || horizon === "14d") {
      // يحدد عدد الأيام المطلوب استعراضها (7 أو 14 يوماً).
      const days = horizon === "7d" ? 7 : 14;
      // يمر على كل يوم بدءاً من الأقدم وحتى اليوم الحالي.
      for (let i = days - 1; i >= 0; i--) {
        // ينشئ نسخة تاريخية لليوم قيد الفحص.
        const d = new Date(now);
        // يطرح عدد الأيام i للوصول إلى التاريخ المطلوب.
        d.setDate(now.getDate() - i);
        // يصيغ مفتاح التاريخ YYYY-MM-DD للبحث عنه في historyMap.
        const key = d.toISOString().slice(0, 10);
        // يجلب سجل اليوم من الخريطة أو ينشئ قيماً صفرية نظيفة (مع حد أدنى لليوم الحالي المفتوح الآن).
        const entry = historyMap[key] || {
          // يسجل دقيقة واحدة لليوم الحالي المفتوح أو صفراً للأيام الخالية.
          activeMinutes: i === 0 ? 1 : 0,
          // يسجل صفحة واحدة لليوم الحالي أو صفراً للأيام الخالية.
          pagesCount: i === 0 ? 1 : 0,
          // يضع عداد الـ PDF بصفر عند عدم وجود نشاط مسجل.
          pdfsCount: 0,
          // يضع دقائق الوضع الداكن بصفر.
          darkModeMinutes: 0,
          // يضع دقائق تلوين HEX بصفر.
          tintMinutes: 0,
          // يسجل زمن المعالجة الابتدائي لليوم الحالي (0.32 مللي ثانية) أو صفراً لغيره.
          totalApplyMs: i === 0 ? 0.32 : 0,
          // يسجل البصمة الابتدائية للذاكرة لليوم الحالي (18 كيلوبايت) أو صفراً لغيره.
          avgFootprintKB: i === 0 ? 18 : 0,
          // يسجل ذروة الذاكرة الابتدائية لليوم الحالي (20 كيلوبايت) أو صفراً لغيره.
          peakFootprintKB: i === 0 ? 20 : 0
          // يغلق كائن القيم الاحتياطية لليوم.
        };
        // يضيف فئة اليوم الجاهزة إلى مصفوفة buckets مع تسمية مختصرة للمحور الأفقي وتاريخ كامل للجدول.
        buckets.push({
          // يصيغ تسمية المحور الأفقي بصورة (شهر/يوم).
          label: `${d.getMonth() + 1}/${d.getDate()}`,
          // يحتفظ بالتاريخ الكامل YYYY-MM-DD للعرض في جدول التفاصيل السفلي.
          fullLabel: key,
          // يفرد كافة المقاييس العددية لليوم داخل كائن الفئة.
          ...entry
          // يغلق كائن الفئة اليومية.
        });
        // يغلق حلقة التجميع اليومي.
      }
      // يعالج الحالة الثانية وهي العرض الأسبوعي المجمّع ("4w" لـ 4 أسابيع أو "8w" لـ 8 أسابيع).
    } else {
      // يحدد عدد الأسابيع المطلوبة (4 أو 8 أسابيع).
      const weeks = horizon === "4w" ? 4 : 8;
      // يمر على كل أسبوع من الأقدم (قبل weeks-1 أسبوع) حتى الأسبوع الحالي (0).
      for (let w = weeks - 1; w >= 0; w--) {
        // يصفر عداد إجمالي دقائق التفعيل للأسبوع قيد التجميع.
        let activeMinutes = 0;
        // يصفر عداد الصفحات المحمية خلال الأسبوع.
        let pagesCount = 0;
        // يصفر عداد ملفات الـ PDF خلال الأسبوع.
        let pdfsCount = 0;
        // يصفر عداد دقائق الوضع الداكن للأسبوع.
        let darkModeMinutes = 0;
        // يصفر عداد دقائق تلوين الشاشة للأسبوع.
        let tintMinutes = 0;
        // يصفر عداد إجمالي وقت المعالج بالمللي ثانية للأسبوع.
        let totalApplyMs = 0;
        // يصفر مجموع متوسطات الذاكرة اليومية لحساب المتوسط الأسبوعي الموزون.
        let kbSum = 0;
        // يصفر عدد الأيام النشطة داخل الأسبوع لقسمة kbSum عليها.
        let kbCount = 0;
        // يصفر متتبع أعلى ذروة ذاكرة مسجلة خلال أيام الأسبوع السبعة.
        let peakKB = 0;

        // يحسب تاريخ آخر يوم في هذا الأسبوع لتوثيق النطاق الزمني في الجدول.
        const endDay = new Date(now);
        // يضبط تاريخ نهاية الأسبوع بطرح (w × 7) أيام من اليوم.
        endDay.setDate(now.getDate() - w * 7);
        // يحسب تاريخ أول يوم في نفس الأسبوع (قبل نهاية الأسبوع بـ 6 أيام).
        const startDay = new Date(now);
        // يضبط تاريخ بداية الأسبوع بطرح (w × 7 + 6) أيام.
        startDay.setDate(now.getDate() - (w * 7 + 6));

        // يجمع بيانات الأيام السبعة المكونة لهذا الأسبوع يوماً تلو الآخر.
        for (let dIdx = 0; dIdx < 7; dIdx++) {
          // ينشئ كائن التاريخ لليوم الفرعي داخل الأسبوع.
          const d = new Date(now);
          // يضبط التاريخ الدقيق لليوم الفرعي.
          d.setDate(now.getDate() - (w * 7 + dIdx));
          // يستخرج مفتاح التاريخ النصي YYYY-MM-DD.
          const key = d.toISOString().slice(0, 10);
          // يبحث عن بيانات هذا اليوم داخل الخريطة التاريخية.
          const item = historyMap[key];
          // إذا وُجد نشاط مسجل في ذلك اليوم، يراكم مقاييسه في مجاميع الأسبوع.
          if (item) {
            // يجمع دقائق التفعيل اليومية إلى حصيلة الأسبوع.
            activeMinutes += item.activeMinutes || 0;
            // يجمع عدد الصفحات إلى حصيلة الأسبوع.
            pagesCount += item.pagesCount || 0;
            // يجمع عدد ملفات الـ PDF إلى حصيلة الأسبوع.
            pdfsCount += item.pdfsCount || 0;
            // يجمع دقائق الوضع الداكن إلى حصيلة الأسبوع.
            darkModeMinutes += item.darkModeMinutes || 0;
            // يجمع دقائق التلوين السداسي إلى حصيلة الأسبوع.
            tintMinutes += item.tintMinutes || 0;
            // يجمع زمن استهلاك المعالج بالمللي ثانية إلى حصيلة الأسبوع.
            totalApplyMs += item.totalApplyMs || 0;
            // يفحص وجود قراءة لمتوسط الذاكرة في ذلك اليوم لإدراجها في حساب المتوسط الأسبوعي.
            if (item.avgFootprintKB) {
              // يضيف متوسط ذاكرة اليوم إلى المجموع kbSum.
              kbSum += item.avgFootprintKB;
              // يزيد عداد الأيام النشطة بمقدار واحد.
              kbCount++;
              // يغلق شرط وجود متوسط الذاكرة.
            }
            // يلتقط القيمة الأعلى لذروة الذاكرة بين الذروة السابقة وذروة هذا اليوم.
            peakKB = Math.max(peakKB, item.peakFootprintKB || 0);
            // يغلق شرط وجود بيانات لليوم الفرعي.
          }
          // يغلق حلقة أيام الأسبوع السبعة.
        }

        // يدرج ملخص الأسبوع المكتمل في مصفوفة buckets للرسم البياني والجدول.
        buckets.push({
          // يمنح الأسبوع تسمية عربية واضحة ("الأسبوع الحالي" أو "قبل X أ").
          label: w === 0 ? "الأسبوع الحالي" : `قبل ${w} أ`,
          // يعرض نطاق التاريخ من البداية للنهاية (MM-DD ← MM-DD) في الجدول التفصيلي.
          fullLabel: `${startDay.toISOString().slice(5, 10)} ← ${endDay.toISOString().slice(5, 10)}`,
          // يقرّب إجمالي دقائق الأسبوع لخانة عشرية واحدة.
          activeMinutes: Number(activeMinutes.toFixed(1)),
          // يضمن احتساب صفحة واحدة على الأقل للأسبوع الحالي المفتوح الآن.
          pagesCount: pagesCount || (w === 0 ? 1 : 0),
          // يدرج إجمالي ملفات الـ PDF للأسبوع.
          pdfsCount,
          // يقرّب دقائق الوضع الداكن الأسبوعية.
          darkModeMinutes: Number(darkModeMinutes.toFixed(1)),
          // يقرّب دقائق تلوين الشاشة الأسبوعية.
          tintMinutes: Number(tintMinutes.toFixed(1)),
          // يقرّب مجموع زمن المعالج الأسبوعي لخانتين عشريتين.
          totalApplyMs: Number(totalApplyMs.toFixed(2)) || (w === 0 ? 0.35 : 0),
          // يحسب المتوسط الحقيقي لاستهلاك الذاكرة عبر قسمة kbSum على kbCount.
          avgFootprintKB: kbCount ? Math.round(kbSum / kbCount) : w === 0 ? 18 : 0,
          // يسجل أعلى ذروة ذاكرة سُجلت خلال الأسبوع.
          peakFootprintKB: peakKB || (w === 0 ? 22 : 0)
          // يغلق كائن الفئة الأسبوعية.
        });
        // يغلق حلقة تجميع الأسابيع.
      }
      // يغلق فرع التجميع الأسبوعي.
    }
    // يعيد مصفوفة الفئات الزمنية الجاهزة للعرض في المخططين والجدول.
    return buckets;
    // يغلق دالة buildBuckets.
  }

  // يعرّف دالة تنسيق الدقائق الزمنية إلى نص عربي مقروء بالساعات والدقائق لبطاقات الملخص والجدول.
  function formatDuration(mins) {
    // يتحقق مما إذا بلغت المدة 60 دقيقة فأكثر لعرضها بصيغة الساعات والدقائق.
    if (mins >= 60) {
      // يستخرج عدد الساعات الكاملة بقسمة الدقائق على 60.
      const h = Math.floor(mins / 60);
      // يحسب الدقائق المتبقية بعد الساعات الكاملة عبر باقي القسمة.
      const m = Math.round(mins % 60);
      // يعيد النص المنسق الجامع بين الساعات والدقائق.
      return `${h} ساعة و ${m} د`;
      // يغلق شرط المدد الطويلة.
    }
    // يعيد المدة بالدقائق المقربة عندما تكون أقل من ساعة كاملة.
    return `${Math.round(mins)} دقيقة`;
    // يغلق دالة تنسيق المدة formatDuration.
  }

  // يعرّف دالة رسم المخطط البياني الأول المزدوج (أعمدة استهلاك الذاكرة بالـ KB + منحنى زمن المعالج بالـ ms).
  function drawResourceChart(buckets) {
    // يجلب عنصر لوحة الرسم الخاصة بموارد النظام من صفحة dashboard.html.
    const canvas = $("resourceChartCanvas");
    // يحصل على سياق الرسم ثنائي الأبعاد 2D للرسم المباشر بدون مكتبات رسوم خارجية ثقيلة.
    const ctx = canvas.getContext("2d");
    // يقرأ العرض الكامل للوحة الرسم بالبكسل.
    const w = canvas.width;
    // يقرأ الارتفاع الكامل للوحة الرسم بالبكسل.
    const h = canvas.height;
    // يمسح أي رسم سابق على اللوحة قبل إعادة رسم الفترة الزمنية الجديدة.
    ctx.clearRect(0, 0, w, h);

    // يحدد الهوامش الداخلية للأضلاع الأربعة لترك مساحة كافية لأرقام المحاور والتسميات السفلية.
    const pad = { top: 24, right: 26, bottom: 36, left: 38 };
    // يحسب العرض الصافي لمنطقة الرسم الفعلي بطرح الهامشين الأيمن والأيسر.
    const pw = w - pad.left - pad.right;
    // يحسب الارتفاع الصافي لمنطقة الرسم بطرح الهامشين العلوي والسفلي.
    const ph = h - pad.top - pad.bottom;

    // يحدد السقف الأعلى لمحور الذاكرة بالكيلوبايت بحيث لا يقل عن 40KB لتتناسب الأعمدة بصرياً.
    const maxKB = Math.max(40, ...buckets.map((b) => b.peakFootprintKB || b.avgFootprintKB || 20));
    // يحدد السقف الأعلى لمنحنى زمن المعالج بالمللي ثانية.
    const maxCpu = Math.max(5, ...buckets.map((b) => b.totalApplyMs || 1));

    // Grid
    // يضبط لون خطوط الشبكة الخلفية بدرجة شفافة هادئة.
    ctx.strokeStyle = "rgba(148,163,184,0.12)";
    // يضبط لون نصوص التدريج الرقمي بالرمادي الفاتح.
    ctx.fillStyle = "#94A3B8";
    // يحدد حجم ونوع خط الأرقام على المحاور.
    ctx.font = "11px system-ui, sans-serif";
    // يرسم 5 خطوط شبكة أفقية متساوية المسافات مع قيمتها المقابلة بالكيلوبايت.
    for (let i = 0; i <= 4; i++) {
      // يحسب الإحداثي الرأسي y لخط الشبكة الحالي.
      const y = pad.top + (ph * i) / 4;
      // يبدأ مسار رسم خط الشبكة الأفقي.
      ctx.beginPath();
      // يضع نقطة البداية عند الهامش الأيسر.
      ctx.moveTo(pad.left, y);
      // يمد الخط أفقياً حتى الهامش الأيمن.
      ctx.lineTo(w - pad.right, y);
      // ينفذ رسم الخط على اللوحة.
      ctx.stroke();
      // يحسب القيمة الرقمية المقابلة لهذا الخط على مقياس الذاكرة maxKB.
      const val = Math.round(maxKB * (1 - i / 4));
      // يحاذي النص لليمين كي يستقر بانتظام يسار منطقة الرسم.
      ctx.textAlign = "right";
      // يطبع قيمة الكيلوبايت بجوار خط الشبكة.
      ctx.fillText(`${val}KB`, pad.left - 4, y + 4);
      // يغلق حلقة رسم الشبكة الخلفية.
    }

    // يحسب العرض المخصص لكل فترة زمنية بقسمة عرض الرسم الصافي على عدد الفئات في buckets.
    const step = pw / buckets.length;

    // Bars for Avg Memory KB
    // يمر على كل فئة زمنية لرسم عمود متوسط استهلاك الذاكرة الخاص بها.
    buckets.forEach((b, idx) => {
      // يحدد عرض العمود المتناسق بحيث لا يتجاوز 30 بكسل.
      const barW = Math.min(30, step * 0.48);
      // يحسب الإحداثي الأفقي x لتوسيط العمود داخل خانته الزمنية.
      const x = pad.left + idx * step + (step - barW) / 2;
      // يحسب ارتفاع العمود نسبياً إلى maxKB مع حد أدنى 3 بكسل ليبقى مرئياً.
      const barH = Math.max(3, ((b.avgFootprintKB || 0) / maxKB) * ph);
      // يحسب نقطة البداية العلوية y للعمود انطلاقاً من قاع منطقة الرسم.
      const y = pad.top + ph - barH;

      // ينشئ تدرجاً لونياً عمودياً سماوياً يميز أعمدة استهلاك الذاكرة.
      const grad = ctx.createLinearGradient(0, y, 0, pad.top + ph);
      // يضع اللون السماوي الساطع في قمة العمود.
      grad.addColorStop(0, "#38BDF8");
      // يضع اللون السماوي الشفاف في قاعدة العمود.
      grad.addColorStop(1, "rgba(56, 189, 248, 0.18)");
      // يسند التدرج اللوني كأداة تعبئة للعمود.
      ctx.fillStyle = grad;
      // يبدأ مسار رسم المستطيل ذي الحواف الدائرية للعمود.
      ctx.beginPath();
      // يرسم العمود بحواف مستديرة بقطر 5 بكسل.
      ctx.roundRect(x, y, barW, barH, 5);
      // يملأ العمود بالتدرج اللوني السماوي.
      ctx.fill();

      // يعيد لون النص للرمادي لكتابة تسمية التاريخ أو الأسبوع أسفل العمود.
      ctx.fillStyle = "#94A3B8";
      // يوسطن النص أفقياً تحت منتصف العمود.
      ctx.textAlign = "center";
      // يكتب تسمية الفترة (b.label) في الهامش السفلي للمخطط.
      ctx.fillText(b.label, x + barW / 2, h - 12);
      // يغلق حلقة رسم أعمدة الذاكرة.
    });

    // Line for CPU Apply Time (ms)
    // يضبط لون القلم للأخضر الزمردي لرسم منحنى زمن المعالجة بالمعالج فوق الأعمدة.
    ctx.strokeStyle = "#22C55E";
    // يحدد سماكة خط المنحنى بـ 2.5 بكسل ليكون واضحاً للمستخدم.
    ctx.lineWidth = 2.5;
    // يبدأ مسار رسم الخط المتصل لزمن المعالج.
    ctx.beginPath();
    // يمر على الفئات الزمنية لتوصيل نقاط زمن المعالجة ببعضها.
    buckets.forEach((b, idx) => {
      // يحسب المركز الأفقي للنقطة في منتصف الخانة الزمنية.
      const cx = pad.left + idx * step + step / 2;
      // يحسب الارتفاع الرأسي للنقطة بناءً على نسبة totalApplyMs إلى maxCpu.
      const cy = pad.top + ph - ((b.totalApplyMs || 0) / maxCpu) * (ph * 0.85);
      // يضع القلم عند النقطة الأولى دون رسم خط سابق لها.
      if (idx === 0) ctx.moveTo(cx, cy);
      // يوصل الخط من النقطة السابقة إلى النقطة الحالية لبقية الفترات.
      else ctx.lineTo(cx, cy);
      // يغلق حلقة بناء مسار المنحنى.
    });
    // يرسم الخط المتصل الكامل لزمن المعالج على اللوحة.
    ctx.stroke();

    // يمر مرة ثانية لرسم نقاط دائرية بارزة فوق كل قراءة على منحنى زمن المعالج.
    buckets.forEach((b, idx) => {
      // يحسب الإحداثي الأفقي لمركز النقطة الدائرية.
      const cx = pad.left + idx * step + step / 2;
      // يحسب الإحداثي الرأسي المطابق لموقع المنحنى في الخطوة السابقة.
      const cy = pad.top + ph - ((b.totalApplyMs || 0) / maxCpu) * (ph * 0.85);
      // يختار اللون الأخضر لتعبئة النقطة الدائرية.
      ctx.fillStyle = "#22C55E";
      // يبدأ مسار الدائرة الصغيرة.
      ctx.beginPath();
      // يرسم دائرة كاملة بنصف قطر 3.5 بكسل حول النقطة.
      ctx.arc(cx, cy, 3.5, 0, Math.PI * 2);
      // يملأ الدائرة باللون الأخضر.
      ctx.fill();
      // يغلق حلقة رسم نقاط المنحنى.
    });
    // يغلق دالة رسم مخطط استهلاك الموارد drawResourceChart.
  }

  // يعرّف دالة رسم المخطط البياني الثاني المخصص لمدة التشغيل بالدقائق مقارنة بالوضع الداكن والتلوين.
  function drawDurationChart(buckets) {
    // يجلب عنصر لوحة الرسم الخاصة بمدة التفعيل من صفحة dashboard.html.
    const canvas = $("durationChartCanvas");
    // يحصل على سياق الرسم ثنائي الأبعاد.
    const ctx = canvas.getContext("2d");
    // يقرأ عرض اللوحة بالبكسل.
    const w = canvas.width;
    // يقرأ ارتفاع اللوحة بالبكسل.
    const h = canvas.height;
    // ينظف اللوحة بالكامل قبل رسم البيانات المحدثة.
    ctx.clearRect(0, 0, w, h);

    // يطبق نفس أبعاد الهوامش المتوازنة المستخدمة في المخطط الأول لتوحيد المظهر البصري.
    const pad = { top: 24, right: 26, bottom: 36, left: 38 };
    // يحسب العرض الصافي للرسم.
    const pw = w - pad.left - pad.right;
    // يحسب الارتفاع الصافي للرسم.
    const ph = h - pad.top - pad.bottom;

    // يحدد القيمة القصوى لمحور الدقائق بحد أدنى 15 دقيقة لضمان تناسق ارتفاع الأعمدة.
    const maxMins = Math.max(15, ...buckets.map((b) => b.activeMinutes || 0));

    // يضبط لون خطوط الشبكة الخلفية.
    ctx.strokeStyle = "rgba(148,163,184,0.12)";
    // يضبط لون نصوص محور الدقائق.
    ctx.fillStyle = "#94A3B8";
    // يحدد خط الأرقام القياسي.
    ctx.font = "11px system-ui, sans-serif";
    // يرسم خطوط الشبكة الخمسة وتدريجات الدقائق المقابلة لها.
    for (let i = 0; i <= 4; i++) {
      // يحسب الموضع الرأسي للخط الحالي.
      const y = pad.top + (ph * i) / 4;
      // يبدأ رسم خط الشبكة.
      ctx.beginPath();
      // يحدد بداية الخط يساراً.
      ctx.moveTo(pad.left, y);
      // يحدد نهاية الخط يميناً.
      ctx.lineTo(w - pad.right, y);
      // ينفذ رسم الخط.
      ctx.stroke();
      // يحسب عدد الدقائق المقابل لهذا المستوى الرأسي.
      const val = Math.round(maxMins * (1 - i / 4));
      // يحاذي رقم الدقائق لليمين.
      ctx.textAlign = "right";
      // يطبع القيمة متبوعة بحرف "د" اختصاراً للدقائق.
      ctx.fillText(`${val}د`, pad.left - 4, y + 4);
      // يغلق حلقة خطوط الشبكة.
    }

    // يحسب المسافة الأفقية المخصصة لكل يوم أو أسبوع.
    const step = pw / buckets.length;
    // يمر على كل فئة زمنية لرسم عمودين متجاورين (إجمالي التعتيم + الوضع الداكن/التلوين).
    buckets.forEach((b, idx) => {
      // يحسب العرض الإجمالي لمجموعة العمودين المتجاورين داخل الخانة.
      const groupW = Math.min(36, step * 0.62);
      // يحسب عرض العمود الفردي الواحد مع ترك مسافة فاصلة صغيرة بينهما.
      const barW = groupW / 2 - 2;
      // يحسب الإحداثي الأفقي للعمود الأول (إجمالي التفعيل).
      const x1 = pad.left + idx * step + (step - groupW) / 2;
      // يحسب الإحداثي الأفقي للعمود الثاني المجاور له (الوضع الداكن والتلوين).
      const x2 = x1 + barW + 4;

      // يحسب ارتفاع العمود الأول نسبةً إلى إجمالي الدقائق maxMins.
      const h1 = Math.max(3, ((b.activeMinutes || 0) / maxMins) * ph);
      // يحسب ارتفاع العمود الثاني المعبر عن كثافة استخدام الوضع الداكن وتلوين HEX.
      const h2 = Math.max(2, (((b.darkModeMinutes || 0) + (b.tintMinutes || 0) * 0.5) / maxMins) * ph);

      // يختار لون العنبر البرتقالي للعمود الأول (إجمالي التعتيم).
      ctx.fillStyle = "#F59E0B";
      // يبدأ رسم العمود الأول.
      ctx.beginPath();
      // يرسم المستطيل المستدير للعمود الأول.
      ctx.roundRect(x1, pad.top + ph - h1, barW, h1, 4);
      // يملأ العمود الأول باللون العنبري.
      ctx.fill();

      // يختار اللون البنفسجي الهادئ للعمود الثاني (الوضع الداكن وتلوين HEX).
      ctx.fillStyle = "#A78BFA";
      // يبدأ رسم العمود الثاني.
      ctx.beginPath();
      // يرسم المستطيل المستدير للعمود الثاني مع ضمان عدم تجاوز سقف منطقة الرسم.
      ctx.roundRect(x2, pad.top + ph - Math.min(ph, h2), barW, Math.min(ph, h2), 4);
      // يملأ العمود الثاني باللون البنفسجي.
      ctx.fill();

      // يضبط اللون الرمادي لتسمية المحور الأفقي أسفل مجموعة العمودين.
      ctx.fillStyle = "#94A3B8";
      // يوسطن النص تحت منتصف المجموعة.
      ctx.textAlign = "center";
      // يطبع اسم اليوم أو الأسبوع.
      ctx.fillText(b.label, x1 + groupW / 2, h - 12);
      // يغلق حلقة رسم أعمدة المدة الزمنية.
    });
    // يغلق دالة رسم مخطط المدة drawDurationChart.
  }

  // يعرّف الدالة الشاملة التي تجلب البيانات، وتحدث بطاقات الملخص الأربع، وترسم المخططين، وتبني الجدول الزمني.
  async function renderAll() {
    // يختار مصدر البيانات بناءً على حالة demoMode (بيانات محاكاة لـ 8 أسابيع أو السجل الفعلي الحقيقي).
    const rawHistory = demoMode ? generateSyntheticMultiWeekHistory() : await loadRealHistory();
    // يقيس الحجم الفعلي بالبايت لكائن السجل لإظهار مدى ضآلة مساحة التخزين المستهلكة للمستخدم.
    const storageBytes = new Blob([JSON.stringify(rawHistory)]).size;
    // يجمّع السجل الخام حسب الأفق الزمني المختار حالياً (7d, 14d, 4w, 8w) عبر دالة buildBuckets.
    const buckets = buildBuckets(rawHistory, currentHorizon);

    // يحسب إجمالي دقائق التفعيل عبر جميع الفئات المعروضة.
    const totalMins = buckets.reduce((s, b) => s + (b.activeMinutes || 0), 0);
    // يحسب إجمالي دقائق استخدام الوضع الداكن عبر الفترة المعروضة.
    const totalDark = buckets.reduce((s, b) => s + (b.darkModeMinutes || 0), 0);
    // يحسب إجمالي دقائق استخدام تلوين الشاشة HEX عبر الفترة المعروضة.
    const totalTint = buckets.reduce((s, b) => s + (b.tintMinutes || 0), 0);
    // يحسب إجمالي زمن معالجة المعالج بالمللي ثانية طوال الفترة المعروضة.
    const totalCpu = buckets.reduce((s, b) => s + (b.totalApplyMs || 0), 0);
    // يحسب إجمالي عدد الصفحات التي حمتها الأداة خلال الفترة.
    const totalPages = buckets.reduce((s, b) => s + (b.pagesCount || 0), 0);
    // يحسب إجمالي ملفات الـ PDF التي جرى تعتيمها خلال الفترة.
    const totalPdfs = buckets.reduce((s, b) => s + (b.pdfsCount || 0), 0);
    // يصفّي الفئات التي سجلت قراءة ذاكرة فعلية لحساب المتوسط الدقيق دون تصفير خادع.
    const activeMemBuckets = buckets.filter((b) => b.avgFootprintKB > 0);
    // يحسب المتوسط العام لاستهلاك الذاكرة بالكيلوبايت عبر الفترة كلها.
    const avgMem = activeMemBuckets.length
      // يقسم مجموع المتوسطات على عدد الفئات النشطة ويقرب لأقرب كيلوبايت.
      ? Math.round(activeMemBuckets.reduce((s, b) => s + b.avgFootprintKB, 0) / activeMemBuckets.length)
      // يستخدم القيمة المرجعية 18 كيلوبايت عند فتح اللوحة لأول مرة قبل تراكم عينات.
      : 18;
    // يستخرج أعلى ذروة استهلاك ذاكرة مسجلة عبر كامل الفترة المعروضة.
    const peakMem = Math.max(20, ...buckets.map((b) => b.peakFootprintKB || 0));

    // يحدّث البطاقة الأولى بإجمالي مدة التشغيل منسقة بالساعات والدقائق.
    $("kpiTotalDuration").textContent = formatDuration(totalMins);
    // يحدّث الوصف الفرعي للبطاقة الأولى بحصة الوضع الداكن من إجمالي التشغيل.
    $("kpiDarkRatio").textContent = `منها ${formatDuration(totalDark)} في الوضع الداكن`;
    // يحدّث البطاقة الثانية بمتوسط استهلاك الذاكرة في النظام بالكيلوبايت.
    $("kpiAvgMemory").textContent = `${avgMem} KB`;
    // يحدّث الوصف الفرعي للبطاقة الثانية بأقصى ذروة مسجلة وحجم سجل التخزين الفعلي بالكيلوبايت.
    $("kpiPeakMemory").textContent = `أقصى ذروة: ${peakMem} KB | حجم السجل: ${(storageBytes / 1024).toFixed(2)} KB`;
    // يحدّث البطاقة الثالثة بإجمالي زمن المعالج التراكمي بالمللي ثانية.
    $("kpiTotalCpuMs").textContent = `${totalCpu.toFixed(2)} ms`;
    // يحدّث البطاقة الرابعة بإجمالي عدد الصفحات المعالجة.
    $("kpiTotalPages").textContent = `${totalPages}`;
    // يحدّث الوصف الفرعي للبطاقة الرابعة بعدد ملفات الـ PDF ودقائق تلوين HEX.
    $("kpiPdfCount").textContent = `شاملة ${totalPdfs} ملف PDF و ${Math.round(totalTint)} د تلوين HEX`;

    // يعرّف قاموس العناوين الوصفية للجدول السفلي حسب المدى الزمني المختار.
    const titles = {
      // وصف عرض الأيام السبعة.
      "7d": "عرض يومي لآخر 7 أيام",
      // وصف عرض الأربعة عشر يوماً.
      "14d": "عرض يومي لآخر 14 يوماً",
      // وصف عرض الأسابيع الأربعة.
      "4w": "عرض أسبوعي لآخر 4 أسابيع",
      // وصف عرض الأسابيع الثمانية.
      "8w": "عرض أسبوعي لآخر 8 أسابيع"
      // يغلق قاموس العناوين الفرعية.
    };
    // يحدّث العنوان الفرعي للجدول مع توضيح ما إذا كانت الأرقام المعروضة محاكاة توضيحية أم حقيقية.
    $("tableModeSubtitle").textContent = titles[currentHorizon] + (demoMode ? " (بيانات محاكاة توضيحية)" : "");

    // يستدعي دالة رسم مخطط الذاكرة والمعالج بالفئات المجمعة.
    drawResourceChart(buckets);
    // يستدعي دالة رسم مخطط مدة التفعيل والأوضاع بنفس الفئات.
    drawDurationChart(buckets);

    // يجلب جسم الجدول التفصيلي لتعبئته بصفوف الفترات الزمنية.
    const tbody = $("historyTableBody");
    // يفرغ الصفوف القديمة قبل بناء الصفوف المحدثة.
    tbody.innerHTML = "";
    // ينسخ مصفوفة الفئات ويعكس ترتيبها ليظهر اليوم أو الأسبوع الأحدث في أعلى الجدول.
    buckets
      // ينشئ نسخة سطحية كي لا يعكس ترتيب المخططات البيانية.
      .slice()
      // يعكس الترتيب الزمني من الأحدث للأقدم.
      .reverse()
      // يبني صفاً جدولياً (tr) لكل فترة زمنية.
      .forEach((b) => {
        // ينشئ عنصر صف جدول جديد في الذاكرة.
        const tr = document.createElement("tr");
        // يملأ خلايا الصف الثمان ببيانات الفترة والتاريخ والمدد والذاكرة والمعالج والصفحات.
        tr.innerHTML = `
          <!-- خلية اسم الفترة والنطاق التاريخي الكامل -->
          <td><strong>${b.label}</strong> <span style="color:#94A3B8;font-size:11.5px;">(${b.fullLabel})</span></td>
          <!-- خلية إجمالي مدة التفعيل -->
          <td>${formatDuration(b.activeMinutes)}</td>
          <!-- خلية مدة تشغيل الوضع الداكن -->
          <td>${formatDuration(b.darkModeMinutes)}</td>
          <!-- خلية مدة تشغيل تلوين HEX -->
          <td>${formatDuration(b.tintMinutes)}</td>
          <!-- خلية متوسط الذاكرة بالكيلوبايت -->
          <td>${b.avgFootprintKB || 0} KB</td>
          <!-- خلية ذروة الذاكرة بالكيلوبايت -->
          <td>${b.peakFootprintKB || 0} KB</td>
          <!-- خلية إجمالي زمن المعالج بالمللي ثانية -->
          <td>${(b.totalApplyMs || 0).toFixed(2)} ms</td>
          <!-- خلية إجمالي الصفحات وحصة ملفات الـ PDF منها -->
          <td>${b.pagesCount} صفحة (${b.pdfsCount} PDF)</td>
        `;
        // يلحق الصف المكتمل بجسم الجدول في الصفحة.
        tbody.appendChild(tr);
        // يغلق حلقة بناء صفوف الجدول.
      });
    // يغلق الدالة الشاملة renderAll.
  }

  // يربط أزرار اختيار الأفق الزمني الأربعة (7 أيام، 14 يوماً، 4 أسابيع، 8 أسابيع) بإعادة الرسم الفوري.
  document.querySelectorAll("[data-horizon]").forEach((btn) => {
    // يسجل حدث النقر على كل زر مدى زمني.
    btn.addEventListener("click", () => {
      // يزيل حالة التفعيل البصري من جميع أزرار شريط المدى الزمني.
      document.querySelectorAll("[data-horizon]").forEach((b) => b.classList.remove("active"));
      // يفعّل الزر الذي اختاره المستخدم حالياً.
      btn.classList.add("active");
      // يحدّث متغير الأفق الزمني النشط بقيمة السمة data-horizon للزر.
      currentHorizon = btn.dataset.horizon;
      // يعيد حساب ورسم كامل اللوحة وفق المدى الزمني الجديد.
      renderAll();
      // يغلق معالج نقر زر المدى الزمني.
    });
    // يغلق حلقة ربط أزرار المدى الزمني.
  });

  // يربط زر محاكاة بيانات الأسابيع بالتبديل الفوري بين العرض التوضيحي والسجل الفعلي للمستخدم.
  $("toggleDemoDataBtn").addEventListener("click", (e) => {
    // يعكس الحالة المنطقية لوضع المحاكاة demoMode.
    demoMode = !demoMode;
    // يضيف أو يزيل الصنف البصري المميز لزر المحاكاة عند تفعيله.
    e.currentTarget.classList.toggle("demo-active", demoMode);
    // يحدّث نص الزر ليعرف المستخدم كيفية العودة لبياناته الحقيقية بنقرة واحدة.
    e.currentTarget.textContent = demoMode ? "✓ العودة للبيانات الحقيقية" : "✨ محاكاة بيانات أسابيع";
    // يعيد رسم البطاقات والمخططات والجدول بالمصدر المختار.
    renderAll();
    // يغلق معالج زر المحاكاة.
  });

  // يربط زر تصدير السجل بتنزيل ملف JSON منسق يحوي كافة إحصائيات الاستهلاك للاحتفاظ بها أو تحليلها.
  $("exportJsonBtn").addEventListener("click", async () => {
    // يجلب البيانات المعروضة حالياً (سواء الحقيقية أو المحاكاة).
    const data = demoMode ? generateSyntheticMultiWeekHistory() : await loadRealHistory();
    // يحوّل الكائن إلى ملف نصي مهيكل بصيغة JSON داخل ذاكرة المتصفح.
    const blob = new Blob([JSON.stringify(data, null, 2)], { type: "application/json" });
    // ينشئ رابط ذاكرة مؤقتاً لملف التصدير.
    const url = URL.createObjectURL(blob);
    // ينشئ عنصر رابط لتنفيذ التنزيل.
    const a = document.createElement("a");
    // يربط العنصر برابط الذاكرة المؤقت.
    a.href = url;
    // يسمي ملف التصدير باسم واضح يتضمن تاريخ اليوم.
    a.download = `mustaqbalat-usage-${new Date().toISOString().slice(0, 10)}.json`;
    // يطلق التنزيل نحو جهاز المستخدم.
    a.click();
    // يحرر رابط الذاكرة المؤقت فوراً بعد إطلاق التنزيل.
    URL.revokeObjectURL(url);
    // يغلق معالج زر التصدير.
  });

  // يربط زر تصفير السجل بمسح كافة بيانات الاستهلاك المخزنة محلياً عند رغبة المستخدم ببدء قياس جديد.
  $("clearHistoryBtn").addEventListener("click", async () => {
    // يلغي وضع المحاكاة إن كان مفعّلاً ليعرض السجل الحقيقي المصفّر.
    demoMode = false;
    // يزيل تنسيق التفعيل عن زر المحاكاة.
    $("toggleDemoDataBtn").classList.remove("demo-active");
    // يعيد النص الأصلي لزر المحاكاة.
    $("toggleDemoDataBtn").textContent = "✨ محاكاة بيانات أسابيع";
    // يتحقق من بيئة الإضافة لمسح السجل من chrome.storage.local.
    if (isExtensionEnv) {
      // يكتب كائناً فارغاً مكان السجل السابق في تخزين الإضافة.
      await new Promise((r) => chrome.storage.local.set({ [STORAGE_KEY_USAGE]: {} }, r));
      // أو يمسحه من localStorage في بيئة الويب.
    } else {
      // يحذف مفتاح السجل من تخزين المتصفح المحلي.
      localStorage.removeItem(STORAGE_KEY_USAGE);
      // يغلق فرع المسح المحلي.
    }
    // يعيد رسم اللوحة فوراً لتظهر القيم المصفّرة النظيفة.
    renderAll();
    // يغلق معالج زر تصفير السجل.
  });

  // يستدعي العرض الشامل فور فتح صفحة لوحة الإحصائيات لرسم البيانات الابتدائية مباشرة.
  renderAll();
  // يغلق الدالة الفورية المعزولة للوحة الإحصائيات وينفذها.
})();
