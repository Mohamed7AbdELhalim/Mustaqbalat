// يعرّف دالة فحص الروابط لاكتشاف الصفحات المحمية التي يمنع المتصفح أمنياً حقن أي إضافة بداخلها.
function isRestrictedBrowserUrl(url) {
  // يتحقق من غياب الرابط تماماً (مثل تبويب قيد الإنشاء) ليصنفه كصفحة داخلية مقيدة مع سبب عربي واضح.
  if (!url) return { restricted: true, reason: "صفحة فارغة أو داخلية للمتصفح" };
  // يحوّل الرابط إلى أحرف صغيرة لتوحيد مقارنة البروتوكولات والنطاقات في الشروط التالية.
  const lower = url.toLowerCase();
  // يبدأ شرطاً مركباً لفحص جميع بروتوكولات الإعدادات الداخلية لمختلف المتصفحات الحديثة.
  if (
    // يفحص صفحات النظام الداخلية لمتصفح جوجل كروم (chrome://).
    lower.startsWith("chrome://") ||
    // يفحص صفحات النظام الداخلية لمتصفح مايكروسوفت إيدج (edge://).
    lower.startsWith("edge://") ||
    // يفحص صفحات الإعدادات الداخلية لمتصفح بريف (brave://).
    lower.startsWith("brave://") ||
    // يفحص صفحات النظام الخاصة بمتصفح أوبرا (opera://).
    lower.startsWith("opera://") ||
    // يفحص صفحات النظام الخاصة بمتصفح فيفالدي (vivaldi://).
    lower.startsWith("vivaldi://") ||
    // يفحص صفحات about: الداخلية في المتصفحات.
    lower.startsWith("about:") ||
    // يفحص صفحات الإضافات الداخلية المعزولة في متصفح فايرفوكس (moz-extension://).
    lower.startsWith("moz-extension://")
    // يغلق قوس شروط بروتوكولات المتصفح الداخلية.
  ) {
    // يبدأ إرجاع نتيجة الفحص الإيجابية بأن الصفحة مقيدة من المتصفح نفسه.
    return {
      // يؤكد أن الصفحة مقيدة لتظهر علامة التنبيه "!" على أيقونة الإضافة وفي نافذة popup.html.
      restricted: true,
      // يزود واجهة المستخدم بتفسير تقني صريح يوضح سبب عدم استجابة هذه الصفحة للتعتيم.
      reason: "صفحات النظام الداخلية للمتصفح تمنع عمل جميع الإضافات لأسباب أمنية."
      // يغلق كائن النتيجة الخاص بصفحات النظام.
    };
    // يغلق كتلة فحص بروتوكولات المتصفح الداخلية.
  }
  // يبدأ شرطاً ثانياً لفحص متاجر الإضافات الرسمية التي تحظر تشغيل سكربتات الإضافات داخلها.
  if (
    // يفحص النطاق الحديث لمتجر كروم الإلكتروني.
    lower.includes("chromewebstore.google.com") ||
    // يفحص المسار الكلاسيكي القديم لمتجر كروم الإلكتروني.
    lower.includes("chrome.google.com/webstore") ||
    // يفحص موقع إضافات موزيلا فايرفوكس الرسمي.
    lower.includes("addons.mozilla.org") ||
    // يفحص متجر إضافات مايكروسوفت إيدج الرسمي.
    lower.includes("microsoftedge.microsoft.com/addons")
    // يغلق قوس شروط متاجر الإضافات.
  ) {
    // يرجع كائن التقييد الخاص بصفحات متاجر الإضافات.
    return {
      // يحدد أن الصفحة مقيدة أمنياً من المتصفح.
      restricted: true,
      // يوضح للمستخدم سبب المنع حتى يتمكن من تمييزه عند مراجعة تبويب بلاغات GitHub.
      reason: "متجر إضافات المتصفح يمنع تشغيل الإضافات الخارجية داخل صفحاته."
      // يغلق كائن النتيجة الخاص بمتاجر الإضافات.
    };
    // يغلق كتلة فحص متاجر الإضافات.
  }
  // يرجع حالة عدم التقييد للصفحات العادية وملفات الـ PDF المسموح للإضافة بالعمل عليها.
  return { restricted: false, reason: "" };
  // يغلق دالة فحص الروابط المقيدة isRestrictedBrowserUrl.
}

// يعرّف دالة غير متزامنة لجلب أحدث إعدادات المستخدم من تخزين الإضافة المحلي ودمجها مع الافتراضيات.
async function getSettings() {
  // يغلّف واجهة chrome.storage.local بوعد برمجي (Promise) لتسهيل استخدامها مع async/await في الدوال اللاحقة.
  return new Promise((resolve) => {
    // يطلب قراءة المفتاح STORAGE_KEY_SETTINGS من المساحة التخزينية المحلية للإضافة.
    chrome.storage.local.get([STORAGE_KEY_SETTINGS], (res) => {
      // يدمج الإعدادات المحفوظة فوق DEFAULT_SETTINGS لضمان عدم نقص أي حقل مستقبلي ويعيد النتيجة.
      resolve(Object.assign({}, DEFAULT_SETTINGS, (res && res[STORAGE_KEY_SETTINGS]) || {}));
      // يغلق دالة استدعاء جلب البيانات من التخزين.
    });
    // يغلق وعد جلب الإعدادات.
  });
  // يغلق دالة getSettings.
}

// يعرّف دالة تحديث الشارة الرقمية/النصية الظاهرة فوق أيقونة الإضافة في شريط المتصفح لكل تبويب نشط.
async function updateBadgeForTab(tabId, url) {
  // يفتح كتلة حماية لتجنب الأخطاء إذا أُغلق التبويب فجأة أثناء التحديث غير المتزامن.
  try {
    // يجلب الإعدادات الحالية عبر دالة getSettings السابقة لمعرفة حالة التفعيل ونسبة السطوع.
    const settings = await getSettings();
    // يفحص رابط التبويب الحالي عبر دالة isRestrictedBrowserUrl لمعرفة ما إذا كان محظوراً من المتصفح.
    const check = isRestrictedBrowserUrl(url);
    // يتحقق من نتيجة الفحص في السطر السابق لتمييز الصفحات المحظورة بشارة تحذيرية.
    if (check.restricted) {
      // يكتب علامة التعجب "!" فوق أيقونة الإضافة لتنبيه المستخدم بأن المتصفح يمنع التعتيم هنا.
      await chrome.action.setBadgeText({ tabId, text: "!" });
      // يلوّن خلفية الشارة بالأحمر الواضح (#EF4444) تماشياً مع علامة التنبيه في السطر السابق.
      await chrome.action.setBadgeBackgroundColor({ tabId, color: "#EF4444" });
      // ينهي الدالة لأن التبويب مقيد ولا تطبق عليه نسب السطوع.
      return;
      // يغلق شرط الصفحات المقيدة.
    }

    // ينشئ متغيراً لاستخراج اسم النطاق الصافي من رابط التبويب لفحص الاستثناءات الفردية.
    let host = "";
    // يحاول تحليل الرابط قياسياً عبر كائن URL لاستخراج hostname.
    try {
      // يستخرج اسم النطاق أو يصنفه كملف محلي ("local-file") في حال بروتوكول file://.
      host = new URL(url).hostname || "local-file";
      // يلتقط أي رابط غير قياسي يتعذر تحليله.
    } catch (_) {
      // يعيّن قيمة احتياطية آمنة عند تعذر استخراج النطاق.
      host = "unknown";
      // يغلق كتلة استخراج النطاق.
    }

    // يتحقق مما إذا كان نطاق الموقع الحالي مدرجاً ضمن قائمة المواقع المستثناة excludedSites في الإعدادات.
    const isExcluded = Array.isArray(settings.excludedSites) && settings.excludedSites.includes(host);
    // يبحث عن وجود إعدادات مخصصة منفردة لهذا النطاق تحديداً داخل siteOverrides.
    const override = (settings.siteOverrides && settings.siteOverrides[host]) || null;
    // يحسب حالة التفعيل الفعلية بدمج التفعيل الشامل globalEnabled مع عدم وجود الموقع في قائمة الاستثناء.
    let active = Boolean(settings.globalEnabled) && !isExcluded;
    // يمنح الأولوية لقرار التفعيل أو التعطيل المخصص للموقع إن وُجد في كائن override السابق.
    if (override && typeof override.enabled === "boolean") active = override.enabled;

    // يفحص ما إذا كانت النتيجة النهائية للتفعيل في السطور السابقة هي الإيقاف على هذا التبويب.
    if (!active) {
      // يعرض كلمة "OFF" على شارة الأيقونة لإعلام المستخدم بأن التعتيم متوقف في هذا الموقع.
      await chrome.action.setBadgeText({ tabId, text: "OFF" });
      // يضبط لون خلفية الشارة إلى الرمادي المحايد (#64748B) الدال على حالة التوقف.
      await chrome.action.setBadgeBackgroundColor({ tabId, color: "#64748B" });
      // ينهي الدالة بعد ضبط شارة الإيقاف.
      return;
      // يغلق شرط حالة التوقف.
    }

    // يستخرج نسبة السطوع المطبقة فعلياً (إما المخصصة للموقع أو العامة) لعرضها على الشارة.
    const b = override && override.brightness ? override.brightness : settings.brightness;
    // يتحقق مما إذا كان الرابط الحالي يشير إلى مستند PDF لتمييزه بشارة خاصة.
    const isPdf = (url || "").toLowerCase().endsWith(".pdf");
    // يحدد نص الشارة بـ "PDF" لمستندات الـ PDF أو بنسبة السطوع المئوية للصفحات العادية.
    const text = isPdf ? "PDF" : `${b}%`;
    // يطبق النص المحسوب في السطر السابق على شارة التبويب الحالي.
    await chrome.action.setBadgeText({ tabId, text });
    // يلوّن خلفية الشارة بلون العنبر الدافئ المميز لهوية مستقبلات (#D97706) تأكيداً لعمل الأداة.
    await chrome.action.setBadgeBackgroundColor({ tabId, color: "#D97706" });
    // يتجاهل بهدوء أخطاء إغلاق التبويب المفاجئ أثناء التحديث.
  } catch (_) {}
  // يغلق دالة تحديث الشارة updateBadgeForTab.
}

// يستمع لحدث تثبيت الإضافة أو تحديثها لتهيئة الإعدادات الافتراضية وحقن المحرك فوراً في التبويبات المفتوحة.
chrome.runtime.onInstalled.addListener(async () => {
  // يقرأ أي إعدادات سابقة مخزنة (في حال التحديث من إصدار أقدم) لئلا تضيع تفضيلات المستخدم.
  const existing = await new Promise((resolve) => {
    // يجلب قيمة STORAGE_KEY_SETTINGS من التخزين المحلي ويعيدها للوعد البرمجي.
    chrome.storage.local.get([STORAGE_KEY_SETTINGS], (r) => resolve(r[STORAGE_KEY_SETTINGS]));
    // يغلق وعد قراءة الإعدادات السابقة.
  });
  // يدمج الإعدادات السابقة إن وُجدت مع DEFAULT_SETTINGS لضمان تفعيل الإضافة افتراضياً عند التثبيت الجديد.
  const merged = Object.assign({}, DEFAULT_SETTINGS, existing || {});
  // يحفظ الكائن المدمج في التخزين المحلي ليصبح متاحاً فوراً للمحرك والنافذة المنبثقة ولوحة الإحصائيات.
  await chrome.storage.local.set({ [STORAGE_KEY_SETTINGS]: merged });

  // Inject into currently open http/https tabs so it works immediately without reload
  // يبدأ كتلة حقن المحرك في التبويبات المفتوحة مسبقاً حتى تعمل الإضافة فوراً دون إجبار المستخدم على إعادة تحميل صفحاته.
  try {
    // يستعلم عن جميع التبويبات المفتوحة حالياً عبر بروتوكولي الويب http وhttps.
    const tabs = await chrome.tabs.query({ url: ["http://*/*", "https://*/*"] });
    // يمر على كل تبويب مفتوح من نتائج الاستعلام في السطر السابق.
    for (const tab of tabs) {
      // يتحقق من امتلاك التبويب لمعرّف رقمي صالح للحقن.
      if (tab.id) {
        // يستدعي واجهة البرمجة النصية في Manifest V3 لحقن ملف المحرك الأساسي داخل التبويب.
        chrome.scripting
          // ينفذ حقن السكربت مع استهداف جميع الإطارات الداخلية (allFrames) لتغطية الإطارات المدمجة أيضاً.
          .executeScript({
            // يحدد التبويب الهدف وشمول كافة إطاراته الفرعية.
            target: { tabId: tab.id, allFrames: true },
            // يحدد ملف المحرك المشترك المسؤول عن طبقات التعتيم والوضع الداكن ومؤشر الاستهلاك.
            files: ["core/mustaqbalat-engine.js"]
            // يغلق كائن خيارات الحقن البرمجي.
          })
          // يتجاهل بهدوء التبويبات المحمية التي يرفض المتصفح حقنها (مثل متجر كروم).
          .catch(() => {});
        // يحدّث شارة الأيقونة لهذا التبويب فوراً بعد حقنه ليعكس نسبة السطوع النشطة.
        updateBadgeForTab(tab.id, tab.url || "");
        // يغلق شرط وجود معرّف التبويب.
      }
      // يغلق حلقة المرور على التبويبات المفتوحة.
    }
    // يتجاهل أي استثناء عام في استعلام التبويبات عند بدء تشغيل المتصفح.
  } catch (_) {}
  // يغلق مستمع حدث التثبيت onInstalled.
});

// يستمع لحدث انتقال المستخدم بين التبويبات لتحديث الشارة بما يطابق حالة الموقع المفتوح حالياً.
chrome.tabs.onActivated.addListener(async ({ tabId }) => {
  // يفتح كتلة حماية لقراءة بيانات التبويب المنشّط للتو.
  try {
    // يجلب معلومات التبويب الكاملة (بما فيها رابطه) عبر معرّفه tabId.
    const tab = await chrome.tabs.get(tabId);
    // يستدعي دالة تحديث الشارة بالاعتماد على رابط التبويب المسترجع في السطر السابق.
    if (tab) updateBadgeForTab(tabId, tab.url || "");
    // يتجاهل الأخطاء العابرة إن أُغلق التبويب في نفس اللحظة.
  } catch (_) {}
  // يغلق مستمع تنشيط التبويبات onActivated.
});

// يستمع لحدث تغير الرابط أو اكتمال تحميل أي تبويب لتحديث الشارة عند التنقل داخل المواقع أو فتح ملف PDF.
chrome.tabs.onUpdated.addListener((tabId, changeInfo, tab) => {
  // يفحص ما إذا اكتمل تحميل الصفحة أو تغير عنوان الرابط الخاص بها.
  if (changeInfo.status === "complete" || changeInfo.url) {
    // يحدّث شارة التبويب بالرابط الجديد لضمان دقة عرض حالة (ON / OFF / PDF / !).
    updateBadgeForTab(tabId, (tab && tab.url) || changeInfo.url || "");
    // يغلق شرط اكتمال التحميل أو تغير الرابط.
  }
  // يغلق مستمع تحديث التبويبات onUpdated.
});

// يستمع لتغير الإعدادات في التخزين المحلي (عندما يحرك المستخدم شريط السطوع في popup.js) لتحديث شارة الأيقونة لحظياً.
chrome.storage.onChanged.addListener(async (changes, area) => {
  // يتحقق من أن التغيير وقع في منطقة التخزين المحلية "local" وشمل مفتاح الإعدادات الرئيسي.
  if (area === "local" && changes[STORAGE_KEY_SETTINGS]) {
    // يفتح كتلة آمنة لجلب التبويب المعروض أمام المستخدم حالياً.
    try {
      // يستعلم عن التبويب النشط في النافذة الحالية للمتصفح.
      const [activeTab] = await chrome.tabs.query({ active: true, currentWindow: true });
      // يتحقق من العثور على التبويب النشط ومعرّفه الصالح.
      if (activeTab && activeTab.id) {
        // يعيد رسم الشارة فوراً لتظهر نسبة السطوع الجديدة التي اختارها المستخدم للتو.
        updateBadgeForTab(activeTab.id, activeTab.url || "");
        // يغلق شرط وجود التبويب النشط.
      }
      // يتجاهل أخطاء الاستعلام عند عدم وجود نافذة متصفح نشطة.
    } catch (_) {}
    // يغلق شرط تغير مفتاح الإعدادات.
  }
  // يغلق مستمع تغييرات التخزين onChanged.
});

// يستمع للرسائل البرمجية الواردة من نافذة الإضافة (popup.js) للتحقق من الروابط وحفظ بلاغات المواقع المعطلة.
chrome.runtime.onMessage.addListener((msg, _sender, sendResponse) => {
  // يتحقق من أن الرسالة الواردة كائن صالح قبل قراءة نوعها.
  if (!msg || typeof msg !== "object") return false;

  // يعالج طلب فحص توافقية رابط التبويب المرسل من popup.js لعرض تنبيه الصفحات المحظورة.
  if (msg.type === "MUSTAQBALAT_CHECK_URL_SUPPORT") {
    // يمرر الرابط المطلوب فحصه إلى دالة isRestrictedBrowserUrl المعرّفة أعلى الملف.
    const info = isRestrictedBrowserUrl(msg.url || "");
    // يرد على نافذة popup.js فوراً بكائن النتيجة (restricted والسبب باللغة العربية).
    sendResponse(info);
    // يعيد true لإبقاء قناة الاتصال مفتوحة وفق معايير رسائل الإضافات.
    return true;
    // يغلق معالجة رسالة فحص توافقية الرابط.
  }

  // يعالج طلب تسجيل موقع غير متوافق محلياً ضمن سجل المواقع التي رفضت العمل مع الإضافة.
  if (msg.type === "MUSTAQBALAT_SAVE_BROKEN_SITE") {
    // يقرأ القائمة الحالية للمواقع المسجلة من التخزين المحلي تحت المفتاح STORAGE_KEY_BROKEN_SITES.
    chrome.storage.local.get([STORAGE_KEY_BROKEN_SITES], (res) => {
      // يستخرج المصفوفة المحفوظة سابقاً أو ينشئ مصفوفة جديدة إن كانت القائمة فارغة.
      const list = Array.isArray(res[STORAGE_KEY_BROKEN_SITES]) ? res[STORAGE_KEY_BROKEN_SITES] : [];
      // ينشئ سجل البلاغ الجديد بدمج معرّف زمني فريد وتاريخ التبليغ مع بيانات الموقع المرسلة في msg.entry.
      const entry = Object.assign(
        // يفتح كائن البيانات التلقائية للبلاغ.
        {
          // يولّد معرّفاً نصياً قصيراً وفريداً مشتقاً من التوقيت الحالي بالأساس 36.
          id: Date.now().toString(36),
          // يوثق التوقيت الدقيق للبلاغ بصيغة ISO القياسية.
          reportedAt: new Date().toISOString()
          // يغلق كائن البيانات التلقائية.
        },
        // يدمج تفاصيل الرابط والوصف القادمة من واجهة المستخدم.
        msg.entry || {}
        // يغلق عملية دمج كائن البلاغ.
      );
      // يدرج البلاغ الجديد في مقدمة المصفوفة ليظهر أولاً في قائمة البلاغات داخل النافذة المنبثقة.
      list.unshift(entry);
      // يقتطع القائمة عند حد أقصى 100 موقع للحفاظ على صغر حجم التخزين دائماً.
      const trimmed = list.slice(0, 100);
      // يحفظ القائمة المحدثة في التخزين المحلي للإضافة.
      chrome.storage.local.set({ [STORAGE_KEY_BROKEN_SITES]: trimmed }, () => {
        // يرسل تأكيد الحفظ والقائمة المحدثة إلى واجهة المستخدم لإعادة عرضها فوراً.
        sendResponse({ ok: true, list: trimmed });
        // يغلق دالة استدعاء الحفظ في التخزين.
      });
      // يغلق دالة استدعاء قراءة قائمة المواقع غير المتوافقة.
    });
    // يعيد true لأن الرد sendResponse يتم بشكل غير متزامن بعد اكتمال القراءة والحفظ في chrome.storage.
    return true;
    // يغلق معالجة رسالة حفظ الموقع غير المتوافق.
  }

  // يعيد false للرسائل غير المعروفة لعدم حجز قناة الرسائل دون داعٍ.
  return false;
  // يغلق المستمع العام لرسائل الخلفية onMessage.
});
