/**
 * Zero-dependency lightweight HTTP server for Mustaqbalat Live Studio & Web Converter.
 * Binds to 0.0.0.0 and serves static assets with permissive CORS & iframe headers.
 */
// يستورد وحدة البروتوكول المدمجة في Node.js لإنشاء خادم الويب المحلي دون أي حزم خارجية، وهو الأساس لتشغيل المنصة الحية (index.html وملفات extension/).
const http = require("http");
// يستورد وحدة نظام الملفات المدمجة لقراءة ملفات المشروع الثابتة من القرص، مكمّلاً وحدة http السابقة بتزويدها بالبيانات المطلوبة للرد على المتصفح.
const fs = require("fs");
// يستورد وحدة المسارات لمعالجة مسارات الملفات وامتداداتها بأمان عبر أنظمة التشغيل، تمهيداً لربط الطلبات الواردة من http بملفات fs.
const path = require("path");

// يحدد رقم المنفذ من متغير البيئة PORT إن وُجد أو يستخدم 3000 افتراضياً، مستفيداً من تهيئة بيئة التشغيل لربط خادم المعاينة بالمنفذ الصحيح.
const PORT = Number(process.env.PORT) || 3000;
// يعيّن عنوان الاستماع إلى جميع واجهات الشبكة (0.0.0.0) بالتكامل مع المنفذ PORT أعلاه لضمان عمل المعاينة السحابية الخارجية بسلاسة.
const HOST = "0.0.0.0";
// يحفظ المسار المطلق لجذر المستودع الحالي ليكون المرجع الآمن لوحدة path عند جلب ملفات index.html وextension/ وconverter/.
const ROOT = __dirname;

// يبدأ تعريف قاموس أنواع الوسائط (MIME) لربط امتداد كل ملف في ROOT بنوع المحتوى الصحيح الذي يتوقعه المتصفح ومحوّل الإضافة.
const MIME_TYPES = {
  // يعرّف نوع ملفات الصفحات العربية بترميز UTF-8 لخدمة index.html وpopup.html وdashboard.html وpdf-viewer.html دون تشوه في الأحرف.
  ".html": "text/html; charset=utf-8",
  // يعرّف نوع أوراق الأنماط بعد HTML مباشرة لضمان تحميل تنسيقات popup.css بشكل سليم داخل نافذة الإضافة والمحاكي.
  ".css": "text/css; charset=utf-8",
  // يعرّف نوع ملفات جافاسكربت بترميز UTF-8 لتشغيل محرك mustaqbalat-engine.js ومحوّل web-addon-converter.js في المتصفح.
  ".js": "application/javascript; charset=utf-8",
  // يعرّف نوع ملفات البيانات المهيكلة لقراءة extension/manifest.json وملفات اللغات _locales عند طلبها من حازم الـ ZIP في الذاكرة.
  ".json": "application/json; charset=utf-8",
  // يعرّف نوع بيان تطبيقات الويب التقدمية (PWA) لدعم ملف manifest.webmanifest المرتبط بالصفحة الرئيسية index.html.
  ".webmanifest": "application/manifest+json; charset=utf-8",
  // يعرّف نوع الصور النقطية الشفافة لعرض أيقونات الإضافة (icon16..icon128.png) وحزمها ثنائياً في أداة التحويل.
  ".png": "image/png",
  // يعرّف نوع الرسوم المتجهة لدعم الشعارات (مثل شعار قبيلة ومرتكز) والرسوم التوضيحية المدمجة في المشروع.
  ".svg": "image/svg+xml",
  // يعرّف نوع أيقونة المتصفح المصغرة تفادياً لأخطاء الطلب التلقائي لـ favicon من المتصفحات.
  ".ico": "image/x-icon",
  // يعرّف نوع مستندات PDF لتمكين قارئ ومعتّم ملفات الـ PDF المدمج (pdf-viewer.html) من عرض المستندات محلياً.
  ".pdf": "application/pdf"
  // يغلق كائن MIME_TYPES بعد استيفاء كافة الامتدادات المستخدمة في بنية مشروع مستقبلات.
};

// ينشئ مثيل خادم HTTP ويمرر دالة معالجة لكل طلب وارد (req) واستجابة صادرة (res) بالاعتماد على الثوابت والقاموس المعرّفين أعلاه.
const server = http.createServer((req, res) => {
  // يفتح كتلة حماية لاصطياد أي استثناء غير متوقع أثناء تحليل الرابط في الطلب الحالي ومنع توقف الخادم.
  try {
    // يحلل الرابط الوارد في req.url باستخدام كائن URL القياسي لفصل المسار النظيف عن معاملات الاستعلام (مثل ?src= في قارئ PDF).
    const parsedUrl = new URL(req.url || "/", `http://${req.headers.host || "localhost"}`);
    // يفك ترميز النصوص في المسار المستخرج من parsedUrl بالسطر السابق لدعم المسارات والأسماء المرمّزة بدقة.
    let pathname = decodeURIComponent(parsedUrl.pathname);
    // يحوّل طلب الجذر الرئيسي "/" الناتج من السطر السابق تلقائياً إلى "/index.html" لفتح منصة مستقبلات الحية مباشرة.
    if (pathname === "/") pathname = "/index.html";

    // Prevent path traversal outside ROOT
    // يدمج مسار الجذر ROOT مع pathname ويطبّعه عبر path.normalize لمنع محاولات الخروج من مجلد المشروع عبر "../".
    const safePath = path.normalize(path.join(ROOT, pathname));
    // يتحقق أمنياً من أن المسار المطبّع safePath لا يزال يبدأ بمسار جذر المشروع ROOT قبل السماح بقراءة أي ملف من القرص.
    if (!safePath.startsWith(ROOT)) {
      // يكتب ترويسة المنع الأمني 403 عند فشل شرط التحقق بالسطر السابق لحماية ملفات النظام خارج المستودع.
      res.writeHead(403, { "Content-Type": "text/plain; charset=utf-8" });
      // ينهي الاستجابة برسالة رفض الوصول استكمالاً لترويسة 403 السابقة.
      res.end("403 Forbidden");
      // يوقف تنفيذ الدالة فوراً لهذا الطلب المرفوض كي لا ينتقل لفحص الملف في السطور التالية.
      return;
      // يغلق كتلة الشرط الأمني لفحص حدود المسار الجذري.
    }

    // يفحص حالة المسار الآمن safePath عبر وحدة fs للتأكد من وجوده فعلياً وكونه ملفاً عادياً وليس مجلداً.
    fs.stat(safePath, (err, stats) => {
      // يتحقق من حدوث خطأ في fs.stat بالسطر السابق أو كون المسار مجلداً لا يمكن بثه كملف.
      if (err || !stats.isFile()) {
        // يرسل رمز الحالة 404 لإبلاغ المتصفح أو أداة التحويل بعدم العثور على الملف المطلوب.
        res.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
        // يختم الرد النصي لرسالة 404 المرتبطة بالترويسة في السطر السابق.
        res.end("404 Not Found");
        // يخرج من دالة الاستدعاء لعدم وجود ملف صالح للبث في الخطوات التالية.
        return;
        // يغلق شرط التحقق من وجود الملف وصحته.
      }

      // يستخرج امتداد الملف بأحرف صغيرة من safePath بعد التأكد من وجوده لربطه بقاموس MIME_TYPES.
      const ext = path.extname(safePath).toLowerCase();
      // يطابق الامتداد المستخرج بالسطر السابق مع قاموس MIME_TYPES أو يعود للنوع الثنائي العام عند عدم التطابق.
      const contentType = MIME_TYPES[ext] || "application/octet-stream";

      // يبدأ كتابة ترويسة النجاح 200 للمتصفح تمهيداً لإرسال محتوى الملف بنوعه المحدد في contentType.
      res.writeHead(200, {
        // يمرر نوع المحتوى المستنتج سابقاً ليتمكن المتصفح من تفسير ملفات الإضافة والأيقونات والـ PDF بشكل سليم.
        "Content-Type": contentType,
        // يسمح بالطلبات العابرة للنطاقات (CORS) لتمكين محاكي النافذة المنبثقة وأداة التحويل من قراءة ملفات extension/ بحرية.
        "Access-Control-Allow-Origin": "*",
        // يمنع التخزين المؤقت القديم لضمان ظهور أي تحديث في ملفات المحرك أو الإضافة فوراً أثناء التطوير والمعاينة.
        "Cache-Control": "no-cache"
        // يغلق كائن ترويسات استجابة HTTP الناجحة.
      });
      // ينشئ تدفق قراءة كفؤ بالذاكرة للملف safePath ويوجهه مباشرة إلى الاستجابة res دون تحميل الملف كاملاً في الذاكرة.
      fs.createReadStream(safePath).pipe(res);
      // يغلق دالة رد النداء الخاصة بفحص معلومات الملف fs.stat.
    });
    // يلتقط أي خطأ برمجي وقع داخل كتلة try أثناء معالجة الرابط أو قراءة المسار.
  } catch (e) {
    // يرسل رمز خطأ الخادم الداخلي 500 عند وقوع استثناء في كتلة catch السابقة.
    res.writeHead(500, { "Content-Type": "text/plain; charset=utf-8" });
    // ينهي الاستجابة بنص توضيحي لخطأ الخادم المرتبط بالترويسة السابقة.
    res.end("500 Internal Server Error");
    // يغلق كتلة معالجة الاستثناءات catch.
  }
  // يغلق دالة معالج الطلبات الممررة إلى http.createServer.
});

// يبدأ تشغيل الخادم فعلياً للاستماع على المنفذ PORT والعنوان HOST المعرّفين في مطلع الملف.
server.listen(PORT, HOST, () => {
  // يطبع رسالة تأكيد الجاهزية في سجل النظام فور نجاح ربط المنفذ في السطر السابق للإعلان عن بدء خدمة المنصة.
  console.log(`Mustaqbalat Studio listening on http://${HOST}:${PORT}`);
  // يغلق دالة رد النداء الخاصة ببدء الاستماع server.listen.
});
